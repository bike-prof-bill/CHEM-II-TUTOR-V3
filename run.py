"""python run.py ch10_cc --per-kind 3 --seed 1
Writes output/<id>.bundle.json, gas/Archetype_<id>.gs and gas/Units.gs (paste both .gs files into Apps Script)."""
import csv, sys, json, argparse, importlib, collections, os
sys.path.insert(0, "archetypes"); import engine
ap = argparse.ArgumentParser(); ap.add_argument("archetype", help="archetype id, or 'all'"); ap.add_argument("--per-kind", type=int, default=3)
ap.add_argument("--seed", type=int, default=1); a = ap.parse_args()
def one(name):
    A = importlib.import_module(name)
    openers = engine.read_openers(f"content_{name}_openers.csv")
    moves   = engine.read_moves(f"content_{name}_moves.csv")
    errors  = engine.read_errors(f"content_{name}_errors.csv")
    limits  = engine.read_limits(f"content_{name}_limits.csv")
    sentences = engine.read_sentences(f"content_{name}_sentences.csv")
    out = engine.build(A, a.per_kind, a.seed, openers, moves, errors, limits, sentences)
    os.makedirs("output", exist_ok=True); os.makedirs("gas", exist_ok=True)
    shipped = bool(out["variants"])                               # a fixed archetype with no scenario row ships nothing (Q versus K until approved)
    # Rule 4: a DRAFT row must not reach a student. A moves or errors row marked DRAFT that applies to a shipped scenario (the
    # opener column blank, or naming that scenario) stops the build of the shipped bundle; rows for scenarios not yet shipped may stay DRAFT.
    drafts = []
    for path, keycol in ((f"content_{name}_moves.csv", "state"), (f"content_{name}_errors.csv", "error id")):
        if not os.path.exists(path): continue
        for r in csv.DictReader(open(path, encoding="utf-8-sig")):
            st = (r.get("status") or "").strip(); key = (r.get(keycol) or "").strip()
            op = next((v.strip() for k, v in r.items() if k and k.lower().startswith("opener") and v), "")
            if key and st.upper().startswith("DRAFT") and (not op or any(o["title"] == op for o in openers)): drafts.append(f"{os.path.basename(path)}: {key}" + (f" ({op})" if op else ""))
    if shipped and drafts:
        print(f"[{name}] NOT SHIPPED: {len(drafts)} DRAFT row(s) apply to a shipped scenario: " + "; ".join(drafts[:8]) + (" ..." if len(drafts) > 8 else ""))
        shipped = False
    if not shipped:
        print(f"[{name}] NOT SHIPPED: " + ("a DRAFT row applies to a shipped scenario" if drafts else f"no scenario in content_{name}_openers.csv") + f", so no gas/Archetype_{name}.gs and no bundle; the test fixture below is the only build.")
        for f in (f"output/{name}.bundle.json", f"gas/Archetype_{name}.gs"):
            if os.path.exists(f): os.remove(f)
    if shipped: json.dump(out, open(f"output/{name}.bundle.json", "w"), indent=1, ensure_ascii=False)
    if shipped: open(f"gas/Archetype_{name}.gs", "w").write(
      "// GENERATED by the factory. Do not edit by hand. content_version " + out["content_version"] + "\n"
      "var ARCHETYPES = (typeof ARCHETYPES === 'undefined') ? {} : ARCHETYPES;\n"
      f"ARCHETYPES[{json.dumps(name)}] = " + json.dumps(out, ensure_ascii=False) + ";\n"
      "if (typeof module !== 'undefined') module.exports = ARCHETYPES;\n")
    print(f"[{name}] {len(out['variants'])} variants, {len(openers)} openers, {len(moves)} move rows. content_version {out['content_version']}")
    dropped = sum(1 for v in out["variants"] if v.get("dropped"))
    if shipped: print(f"[{name}] declared numbers per variant: {min(len(v['expected']) for v in out['variants'])}-{max(len(v['expected']) for v in out['variants'])} | variants with a restated-given intermediate removed: {dropped}")
    tdrop = collections.Counter(t for v in out["variants"] for t in v.get("traps_dropped", []))
    target = 7 if name.startswith("ch10") else 6 if name[:4] in ("ch11", "ch12", "ch13") else 4      # the instructor's targets, 20 Oct 2026
    have = len(out["openers"]); print(f"[{name}] scenarios: {have} of the target {target}" + ("" if have >= target else f"  (needs {target - have} more)"))
    print(f"[{name}] kinds:", dict(collections.Counter(v["kind"] for v in out["variants"])), "| thrown away:", dict(engine.REJECTS), "| traps dropped as lying on a given:", dict(tdrop))
    fx = f"tests/fixtures/content_{name}_openers_allkinds.csv"
    if os.path.exists(fx):                                        # a test-only bundle from retired openers, so every kind stays exercised
        for k in engine.REJECTS: engine.REJECTS[k] = 0
        tb = engine.build(A, a.per_kind, a.seed, engine.read_openers(fx), moves, errors, limits, sentences)
        open(f"gas/Archetype_{name}_test.gs", "w").write("// GENERATED test fixture (retired openers, every kind). Not for Apps Script; not loaded by the servers.\n"
          "var ARCHETYPES_TEST = (typeof ARCHETYPES_TEST === 'undefined') ? {} : ARCHETYPES_TEST;\n" + f"ARCHETYPES_TEST[{json.dumps(name)}] = " + json.dumps(tb, ensure_ascii=False) + ";\nif (typeof module !== 'undefined') module.exports = ARCHETYPES_TEST;\n")
        print(f"[{name}] test fixture: {len(tb['variants'])} variants over {len(engine.read_openers(fx))} retired openers")
    if hasattr(A, "SUBSTANCES"):
        used = {l for o in openers for l in o["fits"]}
        print(f"[{name}] liquids with no scenario yet (never asked):", ", ".join(x[0] for x in A.SUBSTANCES if x[0] not in used) or "none")
    drafts = [s for s, r in moves.items() if not str(r.get("status", "")).strip().lower().startswith("approved")]   # "approved (instructor, …)" counts as approved
    print(f"[{name}] move rows still DRAFT: {len(drafts)} of {len(moves)}")
    for k in engine.REJECTS: engine.REJECTS[k] = 0

